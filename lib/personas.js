/**
 * 还原 JSON 字符串里的转义序列：\n -> 换行、\" -> 引号、\\ -> 反斜杠。
 * 只对"从角色卡里抽出来的字段"用，不对用户手写的普通文本用 ——
 * 否则 Windows 路径里的 \n 会被误伤。
 */
function unescapeJsonString(value) {
  if (typeof value !== 'string' || !value.includes('\\')) return value
  return value.replace(/\\(u[0-9a-fA-F]{4}|.)/g, (_, esc) => {
    switch (esc[0]) {
      case 'n':
        return '\n'
      case 't':
        return '\t'
      case 'r':
        return '\r'
      case 'b':
        return '\b'
      case 'f':
        return '\f'
      case 'u':
        return String.fromCharCode(Number.parseInt(esc.slice(1), 16))
      default:
        return esc
    }
  })
}

/** 从（哪怕结构已经坏掉的）JSON 文本里按字段名抽一个字符串值。 */
function extractJsonField(text, field) {
  const re = new RegExp(`"${field}"\\s*:\\s*"((?:\\\\.|[^"\\\\])*)"`)
  const hit = text.match(re)
  return hit ? unescapeJsonString(hit[1]) : ''
}

/**
 * 尽力把一段文本解析成 SillyTavern V2 / V1 角色卡。
 *
 * 三级容错，因为用户从别处粘过来的卡经常是坏的：
 *   1. 严格 JSON.parse
 *   2. 去掉对象/数组尾逗号后再 parse
 *   3. 结构已损坏时，按字段名正则抽取仍能救回 description 等完整字段
 *
 * @returns {{data: object}|null}
 */
function parseCharacterCard(text) {
  let parsed
  try {
    parsed = JSON.parse(text)
  } catch {
    /* 常见坏法一：尾逗号，往下试 */
  }
  if (!parsed) {
    try {
      parsed = JSON.parse(text.replace(/,\s*([}\]])/g, '$1'))
    } catch {
      /* 坏得更彻底，落到正则抽取 */
    }
  }

  if (parsed && typeof parsed === 'object') {
    const data = parsed.data && typeof parsed.data === 'object' ? parsed.data : parsed
    return { data }
  }

  const salvaged = {}
  let hits = 0
  for (const field of [
    'name',
    'description',
    'personality',
    'scenario',
    'system_prompt',
    'post_history_instructions',
    'mes_example',
  ]) {
    const value = extractJsonField(text, field)
    if (value) {
      salvaged[field] = value
      hits++
    }
  }
  return hits ? { data: salvaged } : null
}

/** 把角色卡字段拼成一段自然语言人设。 */
function composeCardText(data, botName) {
  const fill = (value) =>
    String(value ?? '')
      .replace(/\{\{char\}\}/gi, botName || '你')
      .replace(/\{\{user\}\}/gi, '对方')

  const parts = []
  const name = fill(data.name).trim()
  if (name) parts.push(`你的名字是「${name}」。`)
  if (data.description) parts.push(fill(data.description).trim())
  if (data.personality) parts.push(`【性格】\n${fill(data.personality).trim()}`)
  if (data.scenario) parts.push(`【场景】\n${fill(data.scenario).trim()}`)
  if (data.system_prompt) parts.push(fill(data.system_prompt).trim())
  if (data.post_history_instructions) parts.push(fill(data.post_history_instructions).trim())
  if (data.mes_example) parts.push(`【对话示例】\n${fill(data.mes_example).trim()}`)

  return parts.filter(Boolean).join('\n\n')
}

/**
 * 规范化用户填的人设文本。
 *
 * 用户常直接把一张角色卡 JSON 粘进 personaText。原样塞进系统提示有两个问题：
 * 模型会把整坨 JSON 当成"数据"而不是人设；而且 JSON 里的 \n 是字面两字符，
 * 整段会挤成一行。所以这里先按角色卡解析重组，解析不动才退回原文。
 */
export function normalizePersonaText(raw, botName) {
  const text = String(raw ?? '').trim()
  if (!text) return ''

  if (text.startsWith('{')) {
    const card = parseCharacterCard(text)
    if (card) {
      const composed = composeCardText(card.data, botName)
      if (composed) return composed
    }
  }

  // 不是角色卡就原样用。这里刻意不做转义还原，免得误伤路径里的 \n。
  return text
}

/**
 * 取人设正文：personaText 优先（自定义覆盖），否则按 personaId 取内置；
 * 空值或 'none' = 不注入。
 */
export function resolvePersona(cfg) {
  const custom = normalizePersonaText(cfg?.personaText, cfg?.botName)
  if (custom) return custom
  const id = String(cfg?.personaId ?? 'xiaojingyu').trim()
  if (!id || id === 'none') return ''
  return PERSONAS[id]?.text ?? ''
}

/** 设置页用的人设选项（含"不注入"）。 */
export function personaOptions() {
  return [
    { id: 'none', name: '不注入人设' },
    ...Object.entries(PERSONAS).map(([id, p]) => ({ id, name: p.name })),
  ]
}
